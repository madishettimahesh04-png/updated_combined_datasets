import streamlit as st
import pandas as pd
from rdkit import Chem

from predictor import predict, config, feature_order
from feature_generator import build_features


# ============================================================
# PAGE CONFIG
# ============================================================

st.set_page_config(
    page_title="Hybrid GNN ΔG Predictor",
    page_icon="🧪",
    layout="wide"
)


# ============================================================
# TITLE
# ============================================================

st.title("🧪 Hybrid GNN Solvation Free Energy Predictor")

st.write(
    "Enter the solute and solvent SMILES to generate molecular "
    "descriptors and predict the solvation free energy (ΔG)."
)

st.divider()


# ============================================================
# INPUTS
# ============================================================

col1, col2 = st.columns(2)

with col1:

    st.subheader("Solute")

    solute_smiles = st.text_input(
        "Solute SMILES",
        placeholder="Example: CCO",
        key="solute"
    )

with col2:

    st.subheader("Solvent")

    solvent_smiles = st.text_input(
        "Solvent SMILES",
        placeholder="Example: O",
        key="solvent"
    )


# ============================================================
# GENERATE DESCRIPTORS + PREDICT
# ============================================================

if st.button(
    "🔬 Generate Descriptors & Predict ΔG",
    type="primary",
    use_container_width=True
):

    solute = solute_smiles.strip()
    solvent = solvent_smiles.strip()


    # --------------------------------------------------------
    # Check inputs
    # --------------------------------------------------------

    if not solute or not solvent:

        st.warning(
            "Please enter both Solute and Solvent SMILES."
        )

        st.stop()


    # --------------------------------------------------------
    # Validate SMILES
    # --------------------------------------------------------

    solute_mol = Chem.MolFromSmiles(solute)

    if solute_mol is None:

        st.error("❌ Invalid Solute SMILES.")

        st.stop()


    solvent_mol = Chem.MolFromSmiles(solvent)

    if solvent_mol is None:

        st.error("❌ Invalid Solvent SMILES.")

        st.stop()


    # ========================================================
    # GENERATE DESCRIPTORS
    # ========================================================

    with st.spinner("Generating molecular descriptors..."):

        try:

            descriptor_data = build_features(
                solute,
                solvent
            )

            # Convert dictionary to DataFrame if necessary
            if isinstance(descriptor_data, dict):

                descriptor_df = pd.DataFrame(
                    [descriptor_data]
                )

            else:

                descriptor_df = descriptor_data.copy()


        except Exception as e:

            st.error(
                "❌ Descriptor generation failed."
            )

            st.exception(e)

            st.stop()


    # ========================================================
    # DISPLAY GENERATED DESCRIPTORS
    # ========================================================

    st.success("Descriptors generated successfully.")

    st.divider()

    st.subheader("🔬 Generated Molecular Descriptors")

    # Original descriptors generated by feature_generator.py
    original_features = descriptor_df.copy()

    # Remove identifiers if present
    display_df = original_features.drop(
        columns=[
            "mol_solute",
            "mol_solvent",
            "target"
        ],
        errors="ignore"
    )


    # --------------------------------------------------------
    # Number of generated descriptors
    # --------------------------------------------------------

    number_generated = display_df.shape[1]

    st.metric(
        "Generated Features",
        number_generated
    )


    # --------------------------------------------------------
    # Descriptor table
    # --------------------------------------------------------

    st.dataframe(
        display_df.T.rename(
            columns={0: "Value"}
        ),
        use_container_width=True
    )


    # ========================================================
    # MODEL INPUT FEATURES
    # ========================================================

    st.divider()

    st.subheader("📊 Model Input Features")

    st.write(
        "These are the features after the preprocessing pipeline "
        "used by the trained model."
    )


    # ========================================================
    # PREDICTION
    # ========================================================

    with st.spinner("Running Hybrid GNN prediction..."):

        try:

            prediction = predict(
                solute,
                solvent
            )

            prediction = float(prediction)


        except Exception as e:

            st.error(
                "❌ Prediction failed."
            )

            st.exception(e)

            st.stop()


    # ========================================================
    # RESULT
    # ========================================================

    st.divider()

    st.subheader("🎯 Prediction Result")

    result_col1, result_col2, result_col3 = st.columns(3)

    with result_col1:

        st.metric(
            "Input Features",
            config["input_dim"]
        )

    with result_col2:

        st.metric(
            "Generated Descriptors",
            number_generated
        )

    with result_col3:

        st.metric(
            "Predicted ΔG",
            f"{prediction:.4f} kcal mol⁻¹"
        )


    # ========================================================
    # INPUT SUMMARY
    # ========================================================

    st.divider()

    st.subheader("Prediction Summary")

    summary_col1, summary_col2 = st.columns(2)

    with summary_col1:

        st.write("**Solute SMILES**")

        st.code(solute)

    with summary_col2:

        st.write("**Solvent SMILES**")

        st.code(solvent)
